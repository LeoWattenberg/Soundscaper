test('the E2E gate requires every browser and packaged Electron realm at literal 100%', () => {
	assert.deepEqual(E2E_COVERAGE_CONFIGURATION.thresholds, {
		lines: 100,
		statements: 100,
		functions: 100,
		branches: 100,
	});
	assert.deepEqual(E2E_COVERAGE_CONFIGURATION.requiredSurfaces.map(({ id }) => id), [
		'browser-chromium-framescaper-renderer',
		'browser-chromium-soundscaper-renderer',
		'nightly-electron-framescaper-main',
		'nightly-electron-framescaper-preload',
		'nightly-electron-framescaper-renderer',
		'nightly-electron-soundscaper-main',
		'nightly-electron-soundscaper-preload',
		'nightly-electron-soundscaper-renderer',
	]);
	assert.deepEqual(
		new Set(E2E_COVERAGE_CONFIGURATION.requiredSurfaces.map(({ coverageFormat }) => coverageFormat)),
		new Set(['v8']),
		'every mandatory surface must supply profiles, not only a claimed summary',
	);
	assert.match(E2E_COVERAGE_CONFIGURATION.reason, /separate from Node and unit coverage/u);
});

test('the configuration cannot weaken or omit an E2E coverage dimension', () => {
	const configuration = structuredClone(E2E_COVERAGE_CONFIGURATION);
	configuration.thresholds.branches = 99.99;
	assert.throws(() => parseE2ECoverageConfiguration(configuration), /branches threshold must be exactly 100/u);

	delete configuration.thresholds.functions;
	assert.throws(() => parseE2ECoverageConfiguration(configuration), /functions threshold must be exactly 100/u);
});

test('the executable inventory is canonical, digest-bound and owns every script', () => {
	const fixture = makeFixture();
	const inventory = parseE2EInventory(fixture.inventory, E2E_COVERAGE_CONFIGURATION);

	assert.equal(inventory.digest, digestE2EInventory(inventory));
	assert.equal(inventory.sources.length, fixture.sources.length);
	assert.equal(inventory.scripts.length, fixture.surfaces.length);

	const missingScript = withDigest({
		...fixture.inventory,
		scripts: fixture.inventory.scripts.slice(1),
	});
	assert.throws(
		() => parseE2EInventory(missingScript, E2E_COVERAGE_CONFIGURATION),
		/has no executable scripts/u,
	);

	const reordered = withDigest({
		...fixture.inventory,
		sources: [...fixture.inventory.sources].reverse(),
	});
	assert.throws(
		() => parseE2EInventory(reordered, E2E_COVERAGE_CONFIGURATION),
		/inventory sources must be sorted/u,
	);

	assert.throws(
		() => parseE2EInventory({ ...fixture.inventory, digest: sha256('wrong') }, E2E_COVERAGE_CONFIGURATION),
		/inventory digest does not match/u,
	);
});

