test('incompatible coverage maps and stale revisions cannot be combined', () => {
	const fixture = makeFixture({ sharedBrowserSource: true });
	const inventory = parseE2EInventory(fixture.inventory, E2E_COVERAGE_CONFIGURATION);
	const { manifests, coverageBySurface } = completeEvidence(fixture, inventory);
	const path = fixture.sources.find((source) => fixture.surfaces.slice(0, 2).every((surface) => (
		source.surfaces.includes(surface)
	))).path;
	coverageBySurface[fixture.surfaces[1]][path] = fileCoverage(path, { startLine: 20 });
	manifests[fixture.surfaces[2]] = { ...manifests[fixture.surfaces[2]], sourceRevision: 'f'.repeat(40) };

	const result = analyzeE2ECoverage({
		configuration: E2E_COVERAGE_CONFIGURATION,
		inventory,
		surfaceManifests: manifests,
		coverageBySurface,
		expectedRevision: 'a'.repeat(40),
	});

	assert.match(result.failures.join('\n'), /inventory revision .* does not match the checked-out revision/u);
	assert.match(result.failures.join('\n'), /source revision does not match the inventory/u);
	assert.match(result.failures.join('\n'), /incompatible coverage maps/u);
});

function makeFixture({ sharedBrowserSource = false } = {}) {
	const workspace = mkdtempSync(join(tmpdir(), 'soundscaper-e2e-contract-'));
	workspaces.push(workspace);
	const artifactRoot = join(workspace, 'coverage/e2e');
	mkdirSync(join(workspace, 'src'), { recursive: true });
	mkdirSync(join(artifactRoot, 'executables'), { recursive: true });
	const surfaces = E2E_COVERAGE_CONFIGURATION.requiredSurfaces.map(({ id }) => id);
	const generatedPath = 'generated/nightly-electron-soundscaper-main/main.mjs';
	const generatedArtifactPath = 'executables/soundscaper/main.mjs';
	mkdirSync(join(artifactRoot, 'executables/soundscaper'), { recursive: true });
	const sources = surfaces.map((surface, index) => {
		if (index === 2) {
			writeFileSync(join(artifactRoot, generatedArtifactPath), 'export const packaged = true;\n');
			return {
				path: generatedPath,
				origin: 'artifact',
				artifactPath: generatedArtifactPath,
				sha256: sha256('export const packaged = true;\n'),
				surfaces: [surface],
			};
		}
		const path = `src/surface-${index}.js`;
		const body = `export const surface${index} = true;\n`;
		writeFileSync(join(workspace, path), body);
		return { path, origin: 'repository', sha256: sha256(body), surfaces: [surface] };
	});
	if (sharedBrowserSource) {
		sources[0].surfaces = surfaces.slice(0, 2);
		sources.splice(1, 1);
	}
	const scripts = surfaces.map((surface, index) => {
		const path = `executables/script-${index}.js`;
		const body = `globalThis.surface${index} = true;\n`;
		writeFileSync(join(artifactRoot, path), body);
		const source = sources.find((candidate) => candidate.surfaces.includes(surface));
		const script = {
			id: `${surface}/script-${index}.js`,
			surface,
			artifactPath: path,
			coverageUrl: `file:///__soundscaper_e2e__/${surface}/script-${index}.js`,
			sha256: sha256(body),
			sourceMapSha256: null,
			sources: [source.path],
		};
		return {
			...script,
			coverageKey: e2eExecutableCoverageKey(script),
		};
	});
	const sourceRevision = commitFixtureRepository(workspace);
	const unsigned = {
		schemaVersion: 1,
		kind: 'soundscaper-e2e-executable-inventory',
		sourceRevision,
		sources: [...sources].sort((left, right) => left.path.localeCompare(right.path)),
		scripts: [...scripts].sort((left, right) => left.id.localeCompare(right.id)),
	};
	return {
		workspace,
		artifactRoot,
		surfaces,
		sources: unsigned.sources,
		inventory: withDigest(unsigned),
		generatedPath,
		generatedArtifactPath,
	};
}

function completeEvidence(fixture, inventory) {
	const manifests = {};
	const coverageBySurface = {};
	for (const surface of fixture.surfaces) {
		manifests[surface] = surfaceManifest(fixture, surface);
		coverageBySurface[surface] = {};
		for (const source of inventory.sources.filter((candidate) => candidate.surfaces.includes(surface))) {
			coverageBySurface[surface][source.path] = fileCoverage(source.path);
		}
	}
	return { manifests, coverageBySurface };
}

function surfaceManifest(fixture, surface) {
	return {
		schemaVersion: 1,
		kind: 'soundscaper-e2e-coverage-surface',
		surface,
		sourceRevision: fixture.inventory.sourceRevision,
		inventoryDigest: fixture.inventory.digest,
		coverage: {
			format: 'v8',
			path: 'v8',
			files: [{ path: 'profile.json', byteLength: 3, sha256: sha256('{}\n') }],
		},
		inventoriedScripts: fixture.inventory.scripts
			.filter((script) => script.surface === surface)
			.map(({ id, sha256: digest }) => ({ id, sha256: digest })),
	};
}

function fileCoverage(path, { statements = [1], functions = [1], branches = [[1, 1]], startLine = 1 } = {}) {
	const statementMap = Object.fromEntries(statements.map((_, index) => [
		String(index),
		location(startLine + index),
	]));
	return {
		path,
		statementMap,
		fnMap: Object.fromEntries(functions.map((_, index) => [String(index), {
			name: `function${index}`,
			decl: location(startLine + index),
			loc: location(startLine + index),
			line: startLine + index,
		}])),
		branchMap: Object.fromEntries(branches.map((counts, index) => [String(index), {
			type: 'if',
			line: startLine + index,
			loc: location(startLine + index),
			locations: counts.map(() => location(startLine + index)),
		}])),
		s: Object.fromEntries(statements.map((count, index) => [String(index), count])),
		f: Object.fromEntries(functions.map((count, index) => [String(index), count])),
		b: Object.fromEntries(branches.map((counts, index) => [String(index), counts])),
	};
}

function location(line) {
	return { start: { line, column: 0 }, end: { line, column: 10 } };
}

function v8Entry(url) {
	return {
		scriptId: '1',
		url,
		functions: [{ functionName: '', isBlockCoverage: true, ranges: [{ startOffset: 0, endOffset: 1, count: 1 }] }],
	};
}

function withDigest(inventory) {
	return { ...inventory, digest: digestE2EInventory(inventory) };
}

function sha256(value) {
	return `sha256:${createHash('sha256').update(value).digest('hex')}`;
}

function commitFixtureRepository(repositoryRoot) {
	for (const args of [
		['init', '--quiet'],
		['config', 'user.name', 'Coverage Fixture'],
		['config', 'user.email', 'coverage@example.invalid'],
		['add', 'src'],
		['commit', '--quiet', '-m', 'fixture'],
	]) {
		const outcome = spawnSync('git', args, { cwd: repositoryRoot, encoding: 'utf8' });
		assert.equal(outcome.status, 0, outcome.stderr);
	}
	return spawnSync('git', ['rev-parse', 'HEAD'], { cwd: repositoryRoot, encoding: 'utf8' }).stdout.trim();
}
