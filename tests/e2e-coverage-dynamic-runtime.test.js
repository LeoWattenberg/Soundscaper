after(cleanupE2ECoverageAssemblerFixtures);

test('an authenticated macro inventories only its fixed wrapper source and reuses its attested map', () => {
	const fixture = makeFixture();
	const repeat = readJson(join(fixture.runRoot, BROWSER_PROFILE));
	const dynamicUrl = repeat.result.find(({ url }) => url.startsWith(MACRO_DYNAMIC_COVERAGE_URL_PREFIX))?.url;
	assert.ok(dynamicUrl);
	delete repeat['source-map-cache'][dynamicUrl];
	writeJson(join(fixture.runRoot, 'coverage/v8-browser/browser-repeat.json'), repeat);
	const assembled = assembleE2ECoverageCapture(fixture);
	const script = assembled.captureIndex.scripts.find(({ coverageUrl }) => (
		coverageUrl.includes('/dynamic/browser/soundscaper/renderer/macro-module-v1/')
	));
	assert.ok(script, 'the observed generated executable must be inventoried');
	assert.deepEqual(script.sources, [MACRO_FIXED_COVERAGE_SOURCE_PATH]);
	const fixedSource = assembled.captureIndex.sources.find(({ path }) => (
		path === MACRO_FIXED_COVERAGE_SOURCE_PATH
	));
	assert.deepEqual(fixedSource.surfaces, ['browser-chromium-soundscaper-renderer']);
	assert.equal(assembled.captureIndex.sources.some(({ path }) => path.includes('fixtureMacroExecuted')), false);

	const profiles = readProfiles(join(
		assembled.outputRoot,
		'profiles/browser-chromium-soundscaper-renderer',
	));
	const cache = profiles
		.map((profile) => profile['source-map-cache'][script.coverageUrl])
		.find(Boolean);
	assert.deepEqual(cache.data.sources, [
		`file:///__soundscaper_repo__/${MACRO_FIXED_COVERAGE_SOURCE_PATH}`,
	]);
	assert.doesNotMatch(cache.data.sourcesContent[0], /fixtureMacroExecuted/u,
		'the author-owned program must stay outside the executable source denominator');
	const executable = readFileSync(join(assembled.outputRoot, script.artifactPath), 'utf8');
	assert.match(executable, /fixtureMacroExecuted/u,
		'the exact executed bytes remain available to audit V8 offsets');
});

test('assembly refuses to let the fixed macro wrapper vanish from the union', () => {
	const fixture = makeFixture();
	const { path, profile, url } = macroProfile(fixture);
	profile.result = profile.result.filter((entry) => entry.url !== url);
	delete profile['script-source-cache'][url];
	delete profile['source-map-cache'][url];
	writeJson(path, profile);

	assert.throws(
		() => assembleE2ECoverageCapture(fixture),
		/observed no authenticated macro dynamic module/u,
	);
});

test('assembly rejects spoofed macro source bytes and source maps', () => {
	const sourceSpoof = makeFixture();
	const captured = macroProfile(sourceSpoof);
	captured.profile['script-source-cache'][captured.url] = captured.source.replace(
		MACRO_PROGRAM,
		'globalThis.__fixtureMacroExecuted = false;',
	);
	writeJson(captured.path, captured.profile);
	assert.throws(
		() => assembleE2ECoverageCapture(sourceSpoof),
		/macro dynamic source URL does not match its exact generated bytes/iu,
	);

	const mapSpoof = makeFixture();
	const mapped = macroProfile(mapSpoof);
	mapped.profile['source-map-cache'][mapped.url].data.mappings += 'A';
	writeJson(mapped.path, mapped.profile);
	assert.throws(
		() => assembleE2ECoverageCapture(mapSpoof),
		/stale macro dynamic source-map evidence/iu,
	);
});

