test('assembly inventories and requires an observed emitted script whose map has no sources', () => {
	const fixture = makeFixture();
	const source = 'globalThis.generatedFacade = true;\n';
	const map = {
		file: 'generated-facade.js',
		mappings: '',
		names: [],
		sourceRoot: '',
		sources: [],
		sourcesContent: [],
		version: 3,
		x_soundscaper_source_sha256: [],
	};
	const site = join(fixture.evidenceRoot, 'browser/soundscaper/site');
	write(join(site, 'assets/generated-facade.js'), source);
	writeJson(join(fixture.evidenceRoot, 'browser/soundscaper/source-maps/generated-facade.js.map'), map);
	recordBrowserEvidence(site, 'soundscaper', fixture.expectedRevision);
	const profilePath = join(fixture.runRoot, BROWSER_PROFILE);
	const profile = readJson(profilePath);
	const coverageUrl = 'file:///__soundscaper_e2e__/browser/soundscaper/assets/generated-facade.js';
	profile.result.push(v8Entry(coverageUrl));
	writeJson(profilePath, profile);

	const assembled = assembleE2ECoverageCapture(fixture);
	const script = assembled.captureIndex.scripts.find(({ coverageUrl: url }) => url === coverageUrl);
	assert.ok(script, 'the nonempty emitted executable must remain in the inventory');
	assert.match(script.sources[0], /^generated\/[a-f\d]{64}\.js$/u);
	assert.equal(assembled.captureIndex.sources.find(({ path }) => path === script.sources[0])?.origin, 'artifact');

	const unobserved = makeFixture();
	const unobservedSite = join(unobserved.evidenceRoot, 'browser/soundscaper/site');
	write(join(unobservedSite, 'assets/generated-facade.js'), source);
	writeJson(
		join(unobserved.evidenceRoot, 'browser/soundscaper/source-maps/generated-facade.js.map'),
		map,
	);
	recordBrowserEvidence(unobservedSite, 'soundscaper', unobserved.expectedRevision);
	assert.throws(
		() => assembleE2ECoverageCapture(unobserved),
		/executable equivalence.*generated-facade\.js/u,
	);
});

test('assembly keeps emitted JavaScript raw when its map owns only non-executable sources', () => {
	const fixture = makeFixture();
	const source = 'globalThis.nonExecutableSourceFacade = true;\n';
	const sourcePaths = ['vendor/theme.css', 'vendor/config.json'];
	const sourceContents = ['body { color: CanvasText; }\n', '{"enabled":true}\n'];
	const map = {
		file: 'nonexec-facade.js',
		mappings: 'AAAA',
		names: [],
		sourceRoot: '',
		sources: sourcePaths.map((path) => `file:///fixture/${path}`),
		sourcesContent: sourceContents,
		version: 3,
		x_soundscaper_source_sha256: sourceContents.map(() => null),
	};
	const site = join(fixture.evidenceRoot, 'browser/soundscaper/site');
	write(join(site, 'assets/nonexec-facade.js'), source);
	writeJson(join(
		fixture.evidenceRoot,
		'browser/soundscaper/source-maps/nonexec-facade.js.map',
	), map);
	recordBrowserEvidence(site, 'soundscaper', fixture.expectedRevision);
	const profilePath = join(fixture.runRoot, BROWSER_PROFILE);
	const profile = readJson(profilePath);
	const coverageUrl = 'file:///__soundscaper_e2e__/browser/soundscaper/assets/nonexec-facade.js';
	profile.result.push(v8Entry(coverageUrl));
	writeJson(profilePath, profile);

	const assembled = assembleE2ECoverageCapture(fixture);
	const script = assembled.captureIndex.scripts.find(({ coverageUrl: url }) => url === coverageUrl);
	assert.ok(script, 'nonempty JavaScript must not disappear behind CSS/JSON mappings');
	assert.match(script.sources[0], /^generated\/[a-f\d]{64}\.js$/u);
	assert.equal(assembled.captureIndex.sources.find(({ path }) => path === script.sources[0])?.origin, 'artifact');
});

test('schema-v2 packaged profiles bind the launched app.asar path and bytes to build evidence', () => {
	for (const mutate of [
		(metadata) => { metadata.schemaVersion = 1; },
		(metadata) => { metadata.appAsar.path = '/opt/soundscaper/resources/other.asar'; },
		(metadata) => { metadata.platform = 'darwin'; },
		(metadata) => { metadata.appAsar.afterCollection.byteLength += 1; },
		(metadata) => {
			metadata.appAsar.beforeLaunch.sha256 = '0'.repeat(64);
			metadata.appAsar.afterCollection.sha256 = '0'.repeat(64);
		},
	]) {
		const fixture = makeFixture();
		const path = join(fixture.runRoot, 'coverage/v8-packaged/packaged-soundscaper.json');
		const profile = readJson(path);
		mutate(profile['soundscaper-packaged-runtime']);
		writeJson(path, profile);
		assert.throws(
			() => assembleE2ECoverageCapture(fixture),
			/invalid (?:runtime metadata|app\.asar identity)/iu,
		);
	}
});

function macroProfile(fixture) {
	const path = join(fixture.runRoot, BROWSER_PROFILE);
	const profile = readJson(path);
	const entry = profile.result.find(({ url }) => url.startsWith(MACRO_DYNAMIC_COVERAGE_URL_PREFIX));
	assert.ok(entry, 'the fixture must contain a macro dynamic entry');
	return {
		path,
		profile,
		source: profile['script-source-cache'][entry.url],
		url: entry.url,
	};
}

function replaceMacro(fixture, preludeUrl) {
	const captured = macroProfile(fixture);
	captured.profile.result = captured.profile.result.filter((entry) => entry.url !== captured.url);
	delete captured.profile['script-source-cache'][captured.url];
	delete captured.profile['source-map-cache'][captured.url];
	const source = buildAttestedMacroSandboxModule(`import ${JSON.stringify(preludeUrl)};`, MACRO_PROGRAM);
	const dynamic = macroDynamicCoverageScript({
		repositoryRoot: fixture.repositoryRoot,
		source,
		url: macroDynamicSourceUrl(source),
	});
	captured.profile.result.push(v8Entry(dynamic.coverageUrl));
	captured.profile['script-source-cache'][dynamic.coverageUrl] = source;
	captured.profile['source-map-cache'][dynamic.coverageUrl] = {
		data: dynamic.sourceMap,
		lineLengths: sourceLineLengths(source),
		url: null,
	};
	writeJson(captured.path, captured.profile);
}
