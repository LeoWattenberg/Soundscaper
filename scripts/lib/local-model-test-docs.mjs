const DIRECTORY = 'handbook/src/content/docs/reference/local-models';
const BANNER = '<!-- Generated by `node scripts/docs-local-models.mjs`. Do not edit. -->';
const FIXTURES = Object.freeze({
	'speech-16khz': 'A public-domain excerpt from John F. Kennedy’s inaugural address, with a second of silence added at each end, prepared as mono audio at 16 kHz.',
	'noisy-speech-48khz': 'A public-domain excerpt from John F. Kennedy’s inaugural address resampled to mono 48 kHz, with added reproducible hiss.',
	'visual-subject-frames': 'The public-domain NASA photograph of astronaut Eileen Collins, placed into a frame pack with explicit source-frame timing.',
	'visual-text-frames': 'Frames with the high-contrast words “LOCAL MODEL TEST”, with explicit source-frame timing.',
	'transcript-text': 'A short nonempty text passage supplied to the real tokenizer and embedding network.',
});
const VALIDATION = Object.freeze({
	'voice-activity': 'Speech regions must be nonempty and have valid, ordered boundaries inside the input audio.',
	transcript: 'The transcript must contain nonempty text with valid timing inside the input audio. Exact wording is not compared.',
	'speaker-turns': 'The result must contain speaker turns with valid speaker IDs and timing inside the input audio. The exact number of speakers is not prescribed.',
	'changed-audio': 'Decoded audio must contain finite samples, preserve the expected audio geometry, differ from the input samples, and have a nonzero audible signal. Different file headers alone do not count as a change.',
	'subject-detections': 'Face and object results must have valid source-frame timing, finite confidence scores, and bounded boxes. The subject fixture must produce detections from both models.',
	saliency: 'Frame results must retain their source timing and contain a finite, bounded saliency point for the subject fixture.',
	ocr: 'Text regions must contain nonempty recognized text, valid source-frame timing, finite confidence scores, and bounded boxes.',
	embeddings: 'Embedding vectors must have the expected dimensions and contain finite, nonzero, nonconstant values.',
});
const PLATFORM_NAMES = Object.freeze({
	'darwin-arm64': 'macOS arm64', 'darwin-x64': 'macOS x64',
	'linux-arm64': 'Linux arm64', 'linux-x64': 'Linux x64',
	'win32-arm64': 'Windows arm64', 'win32-x64': 'Windows x64',
});
const SHERPA_TASKS = new Set([
	'voice-activity-detection', 'speech-recognition', 'speaker-segmentation', 'speaker-embedding',
]);

/** Inventory status, not a claim that a particular machine completed inference. */
export function localModelRuntimeAvailability(entry, { nativeRuntime, familySupply }) {
	const familyId = entry.modelId.startsWith('whisper-') ? 'whisper-cpp'
		: SHERPA_TASKS.has(entry.task) ? 'sherpa-onnx-node' : 'onnxruntime-node';
	const sherpa = familyId === 'sherpa-onnx-node';
	const source = sherpa ? nativeRuntime : familySupply.manifests[familyId];
	if (!source?.targets) throw new TypeError(`The model documentation has no ${familyId} runtime inventory.`);
	const targets = sherpa ? source.targets : Object.fromEntries(source.targets.map((target) => [target.id, target]));
	const availablePlatforms = entry.platforms.filter((platform) => {
		const target = platform.replace(/^darwin-/u, 'mac-').replace(/^win32-/u, 'win-');
		return targets[target]?.status === (sherpa ? 'built' : 'authenticated');
	});
	return { familyId, version: sherpa ? source.version : source.runtimeVersion,
		availablePlatforms, missingPlatforms: entry.platforms.filter((platform) => !availablePlatforms.includes(platform)) };
}

function runtimeNotice(availability) {
	const { familyId, version, availablePlatforms, missingPlatforms } = availability;
	if (availablePlatforms.length === 0) {
		return `**The model weights are published, but the required native engine is not yet packaged.** The runtime inventory records no admitted ${familyId} ${version} target for this model. Downloading its weights does not enable processing. The real-model test reports a failure on catalog-supported platforms until the verified native package is supplied.`;
	}
	return `The native runtime inventory contains ${familyId} ${version} payloads for ${availablePlatforms.map((platform) => PLATFORM_NAMES[platform]).join(', ')}. This is package availability, not a claim that a test passed on your machine.`
		+ (missingPlatforms.length ? ` No admitted native payload is recorded for ${missingPlatforms.map((platform) => PLATFORM_NAMES[platform]).join(', ')} even though model weights are listed for those platforms.` : '');
}

function page(title, description, body) {
	return ['---', `title: ${JSON.stringify(title)}`, `description: ${JSON.stringify(description)}`,
		'editUrl: false', '---', '', BANNER, '', body, ''].join('\n');
}

function modelTitle(modelId, cases) {
	return cases.find(({ modelIds }) => modelIds.includes(modelId)).documentation.modelTitles[modelId];
}

function downloadSize(bytes) {
	for (const [divisor, unit] of [[1024 ** 3, 'GiB'], [1024 ** 2, 'MiB'], [1024, 'KiB']]) {
		if (bytes >= divisor) return `${(bytes / divisor).toFixed(2)} ${unit}`;
	}
	return `${String(bytes)} bytes`;
}

function modelPage(entry, cases, runtimeSources) {
	const applicable = cases.filter(({ modelIds }) => modelIds.includes(entry.modelId));
	const { documentation } = applicable[0];
	const pairedIds = [...new Set(applicable.flatMap(({ modelIds }) => modelIds))]
		.filter((modelId) => modelId !== entry.modelId);
	const artifacts = entry.artifacts.map((artifact) => [artifact.fileName, downloadSize(artifact.byteLength)]);
	const availability = localModelRuntimeAvailability(entry, runtimeSources);
	const blocked = availability.availablePlatforms.length === 0;
	const checks = applicable.flatMap((testCase) => [
		`Case: \`${testCase.id}\`; operation: \`${testCase.operation}\`.`, '',
		`Input: ${FIXTURES[testCase.fixtureId]}`, '',
		VALIDATION[testCase.validation], '',
	]);
	const body = [
		documentation.summary, '',
		...(documentation.modelDetails?.[entry.modelId] ? [documentation.modelDetails[entry.modelId], ''] : []),
		'## Current availability {#current-availability}', '', runtimeNotice(availability), '',
		'## Use this model {#use-this-model}', '',
		blocked ? `Once a compatible native runtime is packaged, the intended workflow is **${documentation.menu}**. The steps below describe that workflow; it cannot currently complete with the supplied runtime inventory.`
			: `Open **${documentation.menu}** on a platform with the required native runtime. Local assistance runs in the desktop editor.`, '',
		...documentation.steps.map((step, index) => `${String(index + 1)}. ${step}`), '',
		...(pairedIds.length ? ['This operation also requires '
			+ pairedIds.map((id) => `[${modelTitle(id, cases)}](/reference/local-models/${id}/)`).join(' and ') + '.', ''] : []),
		'## Download and requirements {#download-and-requirements}', '',
		`Model identity: \`${entry.modelId}\`, version **${entry.version}**.`, '',
		`Approximate download size: **${downloadSize(entry.artifacts.reduce((total, artifact) => total + artifact.byteLength, 0))}**. Minimum system memory: **${formatBinaryBytes(entry.minimumMemoryBytes)}**. This catalog requirement refers to total memory, not currently free memory. Inference also needs sufficient free memory, and installation needs working space; memory is not a speed guarantee.`, '',
		`Published platforms: ${entry.platforms.map((platform) => PLATFORM_NAMES[platform] ?? platform).join(', ')}. A matching packaged runtime is also required.`, '',
		'Tools → Model Manager downloads the published artifacts and verifies their recorded SHA-256 digests. Processing uses the installed files locally. Open Storage and verification in Model Manager to inspect notices, repair an installation, or change the storage location.', '',
		table(['Artifact', 'Approximate download size'], artifacts), '',
		'## What the packaged test checks {#what-the-packaged-test-checks}', '',
		...checks,
		'The nightly-with-tests package downloads real model artifacts and requests inference through the packaged runtime. Missing native engines fail the case on catalog-supported platforms. These costly checks run separately from the normal browser suite. A passing run confirms basic model execution and usable output structure; it does not establish perceptual quality or accuracy on your recording.', '',
		'## Review the result {#review-the-result}', '',
		...documentation.limitations.map((limitation) => `- ${limitation}`), '',
		'[Model test coverage and limitations](/reference/local-models/) · [Local processing guide](/help/local-processing/)',
	].join('\n');
	return page(modelTitle(entry.modelId, cases), documentation.summary, body);
}


function indexPage(catalog, cases, runtimeSources) {
	const availability = new Map(catalog.entries.map((entry) =>
		[entry.modelId, localModelRuntimeAvailability(entry, runtimeSources)]));
	const pending = catalog.entries.filter((entry) => availability.get(entry.modelId).availablePlatforms.length === 0);
	const pendingCases = cases.filter(({ modelIds }) => modelIds.some((id) =>
		availability.get(id).availablePlatforms.length === 0));
	const rows = catalog.entries.map((entry) => [
		`[${modelTitle(entry.modelId, cases)}](/reference/local-models/${entry.modelId}/)`,
		entry.task.replaceAll('-', ' '),
		availability.get(entry.modelId).availablePlatforms.length === 0 ? 'Native engine pending' : 'Native payloads recorded; see platform list',
		cases.filter(({ modelIds }) => modelIds.includes(entry.modelId)).map(({ id }) => `\`${id}\``).join(', '),
	]);
	return page('Local model guides and real execution tests',
		'Check the native availability of every published local model and understand its intended workflow and real execution test.', [
		'These guides describe every model in the published catalog and its real execution case. Model weights and native inference engines are separate requirements: an available download does not mean a task can run.', '',
		...(pending.length ? [`**Native runtime packaging is incomplete: ${String(pending.length)} published models in ${String(pendingCases.length)} cases have no admitted native engine target.** Their weights can be downloaded, but their tests fail on catalog-supported platforms until the verified engine packages are provided. The table reflects the committed native runtime inventories, not a successful all-model run.`, ''] : []),
		table(['Model guide', 'Purpose', 'Native runtime inventory', 'Packaged execution case'], rows), '',
		'## Test scope {#test-scope}', '',
		`The catalog contains ${String(catalog.entries.length)} models covered by ${String(cases.length)} execution cases. Speaker diarization uses a segmentation model and an embedding model together. Subject detection uses face and object models together. SigLIP2 testing exercises its image and text networks.`, '',
		'The ordinary browser tests check the interface with a simulated desktop backend. The nightly-with-tests Electron package separately downloads verified model files and requests real inference. Missing native engines are reported as failures on catalog-supported platforms. Expensive model runs are excluded from the normal browser suite. Read the report from a particular package run for its actual results; these pages describe the required checks, not a claim that every build or machine has passed.', '',
		`The published model artifacts total approximately **${downloadSize(catalog.entries.reduce((total, entry) => total + entry.artifacts.reduce((size, artifact) => size + artifact.byteLength, 0), 0))}** before runtime files, fixtures, temporary space, and test output. For the complete run, use a machine with at least **8 GiB free memory**; **16 GiB system memory or more** is a practical starting point. The operation host reserves more memory than some individual catalog minimums. Models run sequentially.`, '',
		'Audio checks reject silence, non-finite samples, and output identical to the input. Text checks require meaningful nonempty result fields. Embedding, detection, and timing checks validate their appropriate numerical structure. Exact sample values, spelling, and rankings are not used as golden outputs.', '',
		'Passing these checks proves basic operation on a small fixture. It does not prove accurate transcription, correct object labels, lossless denoising, or subjective quality. Review results on your own media before applying them.', '',
		'## Operations without published models {#operations-without-published-models}', '',
		'The current published catalog has no models for source separation, dereverberation, beat tracking, audio tagging, word alignment, or editorial generation. Their presence in a menu or operation reference does not make a compatible model available to download. These model tests do not claim to cover those unavailable model installations. Shot detection can also run without a model.', '',
		'[Local processing guide](/help/local-processing/) · [Workflows and operations](/reference/generated/local-assistance/)',
	].join('\n'));
}

export async function generateLocalModelTestDocuments(repositoryRoot, { write = false } = {}) {
	const [catalog, manifest, nativeRuntime, familySupply] = await Promise.all([
		readFile(resolve(repositoryRoot, 'config/local-model-catalog.json'), 'utf8').then(JSON.parse),
		readFile(resolve(repositoryRoot, 'config/local-model-real-test-cases.json'), 'utf8').then(JSON.parse),
		readFile(resolve(repositoryRoot, 'config/assistance-native-runtime-manifest.json'), 'utf8').then(JSON.parse),
		readFile(resolve(repositoryRoot, 'config/assistance-runtime-family-supply-candidates.json'), 'utf8').then(JSON.parse),
	]);
	const cases = validateLocalModelRealTestCases(manifest, catalog);
	const runtimeSources = { nativeRuntime, familySupply };
	const documents = new Map([['index.md', indexPage(catalog, cases, runtimeSources)],
		...catalog.entries.map((entry) => [`${entry.modelId}.md`, modelPage(entry, cases, runtimeSources)])]);
	const directory = resolve(repositoryRoot, DIRECTORY);
	const existing = await readdir(directory).catch((error) => {
		if (error.code === 'ENOENT') return [];
		throw error;
	});
	const stale = existing.filter((fileName) => fileName.endsWith('.md') && !documents.has(fileName))
		.map((fileName) => `${DIRECTORY}/${fileName} (obsolete)`);
	for (const [fileName, source] of documents) {
		const path = resolve(directory, fileName);
		const previous = await readFile(path, 'utf8').catch((error) => {
			if (error.code === 'ENOENT') return null;
			throw error;
		});
		if (previous === source) continue;
		stale.push(`${DIRECTORY}/${fileName}`);
		if (write) {
			await mkdir(directory, { recursive: true });
			await writeFile(path, source, 'utf8');
		}
	}
	return { documentCount: documents.size, stale };
}
