import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import {
	MACRO_MODULE_RECIPE_BOOT,
	MACRO_MODULE_RECIPE_CLOSE,
	MACRO_MODULE_RECIPE_PREFIX,
	MACRO_MODULE_SOURCE_URL_PREFIX,
} from '../../src/common/editor/macro-script/dynamic-source-contract.js';

export const MACRO_FIXED_COVERAGE_SOURCE_PATH =
	'src/common/editor/macro-script/generated-module-wrapper-v1.js';
export const MACRO_DYNAMIC_COVERAGE_URL_PREFIX =
	'file:///__soundscaper_e2e__/dynamic/macro-module-v1/';

const PORTABLE_REPOSITORY_PREFIX = 'file:///__soundscaper_repo__/';
const MACRO_PROTOCOL = 'soundscaper-macro:';
const MACRO_HOST = 'module-v1';
const SHA256 = /^[a-f0-9]{64}$/u;
const BASE64_VLQ = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

/**
 * Authenticate one named macro module and recover its author-owned span.
 *
 * Both hashes are recomputed independently from the captured Debugger source:
 * one owns the versioned fixed recipe and prelude URL, and one owns exactly the
 * bytes supplied by the author. A sourceURL copied onto any other program or
 * wrapper therefore fails closed.
 */
export function attestMacroDynamicSource(url, source) {
	const identity = macroIdentity(url);
	if (typeof source !== 'string') throw new TypeError('Macro dynamic source bytes are missing.');
	const finalLine = `${MACRO_MODULE_SOURCE_URL_PREFIX}${url}\n`;
	if (!source.endsWith(finalLine)) {
		throw new Error('The macro dynamic source URL does not match its exact generated bytes.');
	}
	const body = source.slice(0, -finalLine.length);
	if (!body.startsWith(MACRO_MODULE_RECIPE_PREFIX) || !body.endsWith(MACRO_MODULE_RECIPE_BOOT)) {
		throw new Error('The macro dynamic source does not use the admitted module-v1 recipe.');
	}
	const withoutBoot = body.slice(0, -MACRO_MODULE_RECIPE_BOOT.length);
	const boundary = withoutBoot.lastIndexOf(MACRO_MODULE_RECIPE_CLOSE);
	if (boundary < MACRO_MODULE_RECIPE_PREFIX.length) {
		throw new Error('The macro dynamic source does not contain its fixed wrapper boundary.');
	}
	const programStart = MACRO_MODULE_RECIPE_PREFIX.length;
	const programEnd = boundary;
	const program = withoutBoot.slice(programStart, programEnd);
	const preludeSource = withoutBoot.slice(boundary + MACRO_MODULE_RECIPE_CLOSE.length);
	const preludeModuleUrl = staticPreludeImportUrl(preludeSource);
	const recipeSource = `${MACRO_MODULE_RECIPE_PREFIX}${MACRO_MODULE_RECIPE_CLOSE}${preludeSource}`
		+ MACRO_MODULE_RECIPE_BOOT;
	if (sha256(recipeSource) !== identity.recipeSha256 || sha256(program) !== identity.programSha256) {
		throw new Error('The macro dynamic source URL does not match its exact generated bytes.');
	}
	return Object.freeze({
		...identity,
		body,
		preludeModuleUrl,
		preludeSource,
		program,
		programEnd,
		programStart,
		sourceURL: url,
	});
}

/**
 * Resolve an admitted macro module to one raw-V8 executable and source map.
 * Non-macro URLs are left to the ordinary built-script resolver; every URL in
 * the macro scheme is either authenticated here or rejected.
 */
export function macroDynamicCoverageScript({ repositoryRoot, source, url }) {
	if (!macroProtocol(url)) return null;
	const attestation = attestMacroDynamicSource(url, source);
	const path = resolve(repositoryRoot, MACRO_FIXED_COVERAGE_SOURCE_PATH);
	const fixedSource = readFileSync(path, 'utf8');
	const coverageUrl = `${MACRO_DYNAMIC_COVERAGE_URL_PREFIX}`
		+ `${attestation.recipeSha256}/${attestation.programSha256}.js`;
	return Object.freeze({
		attestation,
		coverageUrl,
		path,
		source,
		sourceMap: macroFixedSourceMap({
			attestation,
			coverageUrl,
			fixedSource,
			source,
		}),
	});
}

/** Recover the sole terminal sourceURL carried by captured generated bytes. */
export function macroDynamicSourceUrl(source) {
	if (typeof source !== 'string') throw new TypeError('Macro dynamic source bytes are missing.');
	const marker = `\n${MACRO_MODULE_SOURCE_URL_PREFIX}`;
	const at = source.lastIndexOf(marker);
	if (at < 0 || !source.endsWith('\n')) {
		throw new Error('The macro dynamic source has no terminal source identity.');
	}
	const url = source.slice(at + marker.length, -1);
	if (url === '' || url.includes('\n') || url.includes('\r')) {
		throw new Error('The macro dynamic source has an invalid terminal source identity.');
	}
	return url;
}

function macroIdentity(value) {
	let url;
	try { url = new URL(value); }
	catch { throw new Error('The macro dynamic source identity is malformed.'); }
	const match = /^\/([a-f0-9]{64})\/([a-f0-9]{64})\.mjs$/u.exec(url.pathname);
	const canonical = match === null ? null
		: `${MACRO_PROTOCOL}//${MACRO_HOST}/${match[1]}/${match[2]}.mjs`;
	if (url.protocol !== MACRO_PROTOCOL || url.hostname !== MACRO_HOST || url.username !== ''
		|| url.password !== '' || url.port !== '' || url.search !== '' || url.hash !== ''
		|| match === null || !SHA256.test(match[1]) || !SHA256.test(match[2]) || value !== canonical) {
		throw new Error('The profiler reported an unsupported macro dynamic source identity.');
	}
	return Object.freeze({ recipeSha256: match[1], programSha256: match[2] });
}

function macroProtocol(value) {
	if (typeof value !== 'string') return false;
	try { return new URL(value).protocol === MACRO_PROTOCOL; }
	catch { return value.startsWith(MACRO_PROTOCOL); }
}

function staticPreludeImportUrl(source) {
	const match = /^import ("(?:[^"\\]|\\.)*");$/u.exec(source);
	if (match === null) throw new Error('The macro dynamic source has no canonical static prelude import.');
	let value;
	try { value = JSON.parse(match[1]); }
	catch { throw new Error('The macro dynamic source has an invalid static prelude URL.'); }
	if (typeof value !== 'string' || JSON.stringify(value) !== match[1]) {
		throw new Error('The macro dynamic source has a non-canonical static prelude URL.');
	}
	let url;
	try { url = new URL(value); }
	catch { throw new Error('The macro dynamic source has a relative static prelude URL.'); }
	if (!['http:', 'https:', 'soundscaper-app:', 'framescaper-app:'].includes(url.protocol)
		|| url.username !== '' || url.password !== '' || url.search !== '' || url.hash !== ''
		|| !/\.js$/u.test(url.pathname)) {
		throw new Error('The macro dynamic source has an unapproved static prelude URL.');
	}
	return url.href;
}

function macroFixedSourceMap({ attestation, coverageUrl, fixedSource, source }) {
	const mappings = Array.from({ length: sourceLineLengths(source).length }, () => '');
	const closeLine = lineAt(source, attestation.programEnd + 1);
	const fixedLines = fixedSource.split(/\r?\n/u);
	const originalLines = [
		lineNamed(fixedLines, 'const __macroMain = async (_sound) => {'),
		lineNamed(fixedLines, '\t"use strict";'),
		lineNamed(fixedLines, '};'),
		lineNamed(fixedLines, "import './sandbox-prelude.js';"),
		lineNamed(fixedLines, 'globalThis.__macroBoot(__macroMain);'),
	];
	let previousOriginalLine = 0;
	for (const [generatedLine, originalLine] of [
		[0, originalLines[0]],
		[1, originalLines[1]],
		[closeLine, originalLines[2]],
		[closeLine + 1, originalLines[3]],
		[closeLine + 2, originalLines[4]],
	]) {
		mappings[generatedLine] = encodeSegment([0, 0, originalLine - previousOriginalLine, 0]);
		previousOriginalLine = originalLine;
	}
	return Object.freeze({
		file: coverageUrl,
		mappings: mappings.join(';'),
		names: [],
		sourceRoot: '',
		sources: [`${PORTABLE_REPOSITORY_PREFIX}${MACRO_FIXED_COVERAGE_SOURCE_PATH}`],
		sourcesContent: [fixedSource],
		version: 3,
		x_soundscaper_source_sha256: [sha256(fixedSource)],
	});
}

function lineNamed(lines, value) {
	const matches = lines.flatMap((line, index) => line === value ? [index] : []);
	if (matches.length !== 1) throw new Error(`The macro fixed coverage source lost ${value}.`);
	return matches[0];
}

function lineAt(source, offset) {
	return source.slice(0, offset).split('\n').length - 1;
}

function sourceLineLengths(source) {
	const lines = source.split('\n');
	if (lines.length > 1 && lines.at(-1) === '') lines.pop();
	return lines.map((line) => line.length);
}

function encodeSegment(values) {
	return values.map(encodeVlq).join('');
}

function encodeVlq(value) {
	let remaining = value < 0 ? ((-value) << 1) + 1 : value << 1;
	let encoded = '';
	do {
		let digit = remaining & 31;
		remaining >>>= 5;
		if (remaining > 0) digit |= 32;
		encoded += BASE64_VLQ[digit];
	} while (remaining > 0);
	return encoded;
}

function sha256(value) {
	return createHash('sha256').update(value).digest('hex');
}
