function compareText(left, right) {
	return left < right ? -1 : left > right ? 1 : 0;
}

export function escapeMarkdownTableCell(value) {
	return String(value ?? '')
		.replaceAll('\\', '\\\\')
		.replaceAll('|', '\\|')
		.replace(/\r?\n/gu, ' ');
}

function table(headers, rows) {
	const line = (cells) => `| ${cells.map(escapeMarkdownTableCell).join(' | ')} |`;
	return [
		line(headers),
		line(headers.map(() => '---')),
		...rows.map(line),
	].join('\n');
}

function page({ title, description, order, body }) {
	return [
		'---',
		`title: ${JSON.stringify(title)}`,
		`description: ${JSON.stringify(description)}`,
		'editUrl: false',
		'sidebar:',
		`  order: ${String(order)}`,
		'---',
		'',
		GENERATED_BANNER,
		'',
		body.trim(),
		'',
	].join('\n');
}

function productNames(products) {
	return products.map(({ name }) => name).join(', ');
}

function assertProducts(products) {
	if (!Array.isArray(products) || products.length === 0) {
		throw new TypeError('At least one product profile is required.');
	}
	for (const product of products) {
		if (!product || typeof product !== 'object' || typeof product.id !== 'string' || typeof product.name !== 'string') {
			throw new TypeError('Every documentation product must have an id and name.');
		}
	}
}

export function renderCommandReference({
	manifest,
	implementedStatus,
	products,
	source,
	isProductCommandDisabled,
}) {
	assertProducts(products);
	if (!manifest || typeof manifest !== 'object') throw new TypeError('The action manifest is required.');
	if (typeof isProductCommandDisabled !== 'function') throw new TypeError('The product command filter is required.');
	if (!source?.commit || !source?.url || !source?.version) throw new TypeError('Audacity source provenance is required.');

	const commands = [];
	for (const definition of Object.values(manifest)) {
		if (definition?.status !== implementedStatus || definition.menuVisible === false) continue;
		if (typeof definition.id !== 'string' || typeof definition.label !== 'string') {
			throw new TypeError('Every implemented action must have an id and label.');
		}
		const availableProducts = products.filter((product) => !isProductCommandDisabled(
			definition.id,
			product.shortcuts?.disabledCommandIds ?? [],
		));
		if (availableProducts.length === 0) continue;
		commands.push({
			id: definition.id,
			label: definition.label,
			shortcut: definition.shortcut || '—',
			locations: Array.isArray(definition.locations) ? definition.locations.join('; ') : '—',
			products: productNames(availableProducts),
			origin: definition.origin === 'upstream' ? 'Audacity' : 'Soundscaper local',
		});
	}
	commands.sort((left, right) => compareText(left.label, right.label) || compareText(left.id, right.id));

	const shortCommit = source.commit.slice(0, 12);
	const body = [
		`This inventory contains commands marked as implemented in the runtime action manifest. Audacity-derived entries are reviewed against Audacity ${source.version} at [\`${shortCommit}\`](${source.url}). Local entries are identified separately.`,
		'',
		'Product availability follows each product profile’s command filters. “—” means that no default shortcut is assigned; it does not mean the command is unavailable.',
		'',
		table(
			['Command', 'Command ID', 'Default shortcut', 'Menu location', 'Products', 'Origin'],
			commands.map((command) => [
				command.label,
				`\`${command.id}\``,
				command.shortcut,
				command.locations,
				command.products,
				command.origin,
			]),
		),
	].join('\n');
	return page({
		title: 'Commands and shortcuts',
		description: 'Implemented commands, default shortcuts, product availability, and source provenance.',
		order: 1,
		body,
	});
}

function audioRuntimeRequirement(descriptor) {
	if (descriptor.backend === 'native-wav' || descriptor.backend === 'native-aiff') return 'Built in';
	if (descriptor.backend === 'custom-ffmpeg') {
		return 'FFmpeg runtime required; settings determine the encoder and container';
	}
	if (descriptor.backend !== 'ffmpeg') throw new RangeError(`Unknown audio export backend: ${String(descriptor.backend)}.`);
	const encoders = (descriptor.requiredEncoders ?? []).join(', ') || 'runtime-selected';
	const muxers = (descriptor.requiredMuxers ?? [])
		.map((alternatives) => Array.isArray(alternatives) ? alternatives.join(' or ') : String(alternatives))
		.join(', ') || 'runtime-selected';
	return `FFmpeg runtime required (encoders: ${encoders}; muxers: ${muxers})`;
}

function videoRuntimeRequirement(descriptor) {
	const encoders = (descriptor.requiredEncoders ?? []).join(', ') || 'runtime-selected';
	const muxers = (descriptor.requiredMuxers ?? []).join(', ') || 'runtime-selected';
	return `FFmpeg runtime required (encoders: ${encoders}; muxers: ${muxers})`;
}

function assertAudioFormatInventory(audioFormatIds, audioFormats) {
	if (!Array.isArray(audioFormatIds) || !audioFormats || typeof audioFormats !== 'object') {
		throw new TypeError('The audio export format registries are required.');
	}
	const declared = [...audioFormatIds].sort(compareText);
	const described = Object.keys(audioFormats).sort(compareText);
	if (declared.length !== new Set(declared).size || declared.join('\n') !== described.join('\n')) {
		throw new Error('The editor audio export format list and descriptor registry must contain the same unique IDs.');
	}
}

export function renderFormatReference({ products, audioFormatIds, audioFormats, videoFormats }) {
	assertProducts(products);
	assertAudioFormatInventory(audioFormatIds, audioFormats);
	if (!videoFormats || typeof videoFormats !== 'object') throw new TypeError('The video export format registry is required.');

	const audioProducts = products.filter((product) => product.exportChoices?.includes('audio'));
	const videoProducts = products.filter((product) => (
		product.exportChoices?.includes('video') && product.capabilities?.videoExport !== false
	));
	const audioRows = Object.values(audioFormats)
		.map((descriptor) => [
			descriptor.label,
			descriptor.extension ? `.${descriptor.extension}` : 'Chosen at export',
			`${descriptor.codec} / ${descriptor.container}`,
			descriptor.lossless === true ? 'Lossless' : descriptor.lossless === false ? 'Lossy' : 'Depends on settings',
			String(descriptor.maximumChannels),
			audioRuntimeRequirement(descriptor),
			productNames(audioProducts),
		])
		.sort((left, right) => compareText(left[0], right[0]));
	const videoRows = Object.values(videoFormats)
		.map((descriptor) => [
			descriptor.label,
			`.${descriptor.extension}`,
			`${descriptor.videoCodec} video; ${descriptor.audioCodec} audio / ${descriptor.container}`,
			videoRuntimeRequirement(descriptor),
			productNames(videoProducts),
		])
		.sort((left, right) => compareText(left[0], right[0]));

	const body = [
		'These are the concrete formats registered by the current export runtime. Product availability comes from the product profiles.',
		'',
		'“Built in” means the application has a native writer for that format. “FFmpeg runtime required” is conditional: the table does not promise that the FFmpeg runtime can be loaded in every build or environment, or that an arbitrary replacement runtime contains the listed encoder and muxer.',
		'',
		'## Audio',
		'',
		table(
			['Format', 'Extension', 'Codec / container', 'Fidelity', 'Maximum channels', 'Runtime requirement', 'Products'],
			audioRows,
		),
		'',
		'## Video',
		'',
		table(
			['Format', 'Extension', 'Codecs / container', 'Runtime requirement', 'Products'],
			videoRows,
		),
	].join('\n');
	return page({
		title: 'Export formats',
		description: 'Registered audio and video export formats and their runtime requirements.',
		order: 2,
		body,
	});
}

function reviewedLabel(labels, key, kind) {
	const label = labels[key];
	if (!label) throw new Error(`No reviewed documentation label exists for ${kind} ${key}.`);
	return label;
}

function renderFeatureRows(products, field, labels, kind) {
	const keys = new Set(products.flatMap((product) => Object.keys(product[field] ?? {})));
	return [...keys]
		.map((key) => ({ key, label: reviewedLabel(labels, key, kind) }))
		.sort((left, right) => compareText(left.label, right.label) || compareText(left.key, right.key))
		.map(({ key, label }) => [
			label,
			...products.map((product) => product[field]?.[key] === true ? 'Enabled' : 'Not enabled'),
		]);
}

function familyNames(families) {
	if (!Array.isArray(families)) return 'None';
	return families.map((family) => reviewedLabel(FAMILY_LABELS, family, 'format family')).join(', ');
}

export function renderCapabilityReference({ products }) {
	assertProducts(products);
	const featureRows = renderFeatureRows(products, 'capabilities', CAPABILITY_LABELS, 'capability');
	const applicationFeatureRows = renderFeatureRows(
		products,
		'applicationFeatures',
		APPLICATION_FEATURE_LABELS,
		'application feature',
	);
	const familyRows = products.map((product) => [
		product.name,
		familyNames(product.importChoices),
		familyNames(product.exportChoices),
	]);
	const featureHeaders = ['Capability', ...products.map(({ name }) => name)];
	const sections = [
		'This page reflects the current product profiles. “Enabled” means that the profile exposes that authoring or runtime capability. A disabled capability can still be preserved when a project is opened across products; this table does not claim that it can be edited.',
		'',
		'## Import and export families',
		'',
		table(['Product', 'Import families', 'Export families'], familyRows),
		'',
		'Families describe product entry points, not every file extension a decoder might accept. See [Export formats](/reference/generated/formats/) for concrete output formats and runtime conditions.',
		'',
		'## Editing and project capabilities',
		'',
		table(featureHeaders, featureRows),
	];
	if (applicationFeatureRows.length > 0) {
		sections.push(
			'',
			'## Product-specific application features',
			'',
			table(featureHeaders, applicationFeatureRows),
		);
	}
	return page({
		title: 'Product capabilities',
		description: 'Soundscaper and Framescaper import, export, editing, and project capabilities.',
		order: 3,
		body: sections.join('\n'),
	});
}

function validateDocumentMap(documents) {
	if (!(documents instanceof Map) || documents.size === 0) throw new TypeError('Generated reference documents are required.');
	for (const [name, content] of documents) {
		if (basename(name) !== name || !/^[a-z0-9-]+\.md$/u.test(name)) {
			throw new RangeError(`Unsafe generated reference document name: ${String(name)}.`);
		}
		if (typeof content !== 'string' || !content.endsWith('\n')) {
			throw new TypeError(`Generated reference document ${name} must be newline-terminated text.`);
		}
	}
}

async function readIfPresent(path) {
	try {
		return await readFile(path, 'utf8');
	} catch (error) {
		if (error?.code === 'ENOENT') return null;
		throw error;
	}
}

async function generatedMarkdownNames(directory) {
	try {
		return (await readdir(directory, { withFileTypes: true }))
			.filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
			.map(({ name }) => name)
			.sort(compareText);
	} catch (error) {
		if (error?.code === 'ENOENT') return [];
		throw error;
	}
}

export async function syncReferenceDocuments(repositoryRoot, documents, { write = true } = {}) {
	validateDocumentMap(documents);
	const outputDirectory = resolve(repositoryRoot, GENERATED_REFERENCE_DIRECTORY);
	const expectedNames = [...documents.keys()].sort(compareText);
	const actualNames = await generatedMarkdownNames(outputDirectory);
	const unexpectedNames = actualNames.filter((name) => !documents.has(name));
	const staleNames = [...unexpectedNames];

	for (const name of expectedNames) {
		const current = await readIfPresent(join(outputDirectory, name));
		if (current !== documents.get(name)) staleNames.push(name);
	}
	staleNames.sort(compareText);
	if (!write || staleNames.length === 0) return Object.freeze({ stale: Object.freeze(staleNames) });

	await mkdir(outputDirectory, { recursive: true });
	for (const name of expectedNames) {
		const path = join(outputDirectory, name);
		if (await readIfPresent(path) !== documents.get(name)) await writeFile(path, documents.get(name), 'utf8');
	}
	for (const name of unexpectedNames) await rm(join(outputDirectory, name));
	return Object.freeze({ stale: Object.freeze(staleNames) });
}

function moduleUrl(repositoryRoot, relativePath) {
	return pathToFileURL(resolve(repositoryRoot, relativePath)).href;
}

export async function loadReferenceSources(repositoryRoot) {
	const [actions, media, video, products, exportSettings] = await Promise.all([
		import(moduleUrl(repositoryRoot, 'src/common/editor/audacity-action-parity.js')),
		import(moduleUrl(repositoryRoot, 'src/common/editor/media-export.js')),
		import(moduleUrl(repositoryRoot, 'src/common/editor/video-export.js')),
		import(moduleUrl(repositoryRoot, 'src/common/products.js')),
		import(moduleUrl(repositoryRoot, 'src/common/editor/controller/export-settings.ts')),
	]);
	return Object.freeze({ actions, media, video, products, exportSettings });
}

export function renderReferenceDocuments({ actions, media, video, products, exportSettings }) {
	const productProfiles = products.PRODUCT_IDS.map((id) => products.PRODUCT_PROFILES[id]);
	return new Map([
		['commands.md', renderCommandReference({
			manifest: actions.AUDACITY_ACTION_MANIFEST,
			implementedStatus: actions.AUDACITY_ACTION_STATUS.IMPLEMENTED,
			products: productProfiles,
			source: actions.AUDACITY_ACTION_SOURCE,
			isProductCommandDisabled: actions.isAudacityShortcutCommandDisabled,
		})],
		['formats.md', renderFormatReference({
			products: productProfiles,
			audioFormatIds: exportSettings.EDITOR_EXPORT_FORMATS,
			audioFormats: media.MEDIA_EXPORT_FORMATS,
			videoFormats: video.VIDEO_EXPORT_FORMATS,
		})],
		['product-capabilities.md', renderCapabilityReference({ products: productProfiles })],
	]);
}

export async function generateReferenceDocuments(repositoryRoot, { write = true } = {}) {
	const sources = await loadReferenceSources(repositoryRoot);
	const documents = renderReferenceDocuments(sources);
	const result = await syncReferenceDocuments(repositoryRoot, documents, { write });
	return Object.freeze({ ...result, documentCount: documents.size });
}
