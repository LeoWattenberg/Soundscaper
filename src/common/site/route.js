import { getLocaleDescriptor } from '../i18n/locales.js';
import { isTransferRoutePath } from '../transfer/transfer-routes.js';

const DESKTOP_PRODUCT_ID = typeof __SCAPE_PRODUCT__ === 'string' && __SCAPE_PRODUCT__ === 'framescaper'
	? 'framescaper'
	: 'soundscaper';

export async function resolveApplicationRoute(scope = globalThis) {
	const desktop = scope.scapeDesktop?.v1;
	if (desktop) {
		const environment = await desktop.getEnvironment();
		return createRoute(DESKTOP_PRODUCT_ID, environment?.locale, true, true);
	}
	if (isTransferRoutePath(scope.location?.pathname)) return mountTransferDocument(scope);
	if (scope.location?.pathname === '/') scope.location.replace('/en/');

	const segments = String(scope.location?.pathname || '/')
		.split('/')
		.filter(Boolean);
	const productId = segments[0] === 'framescaper' ? 'framescaper' : 'soundscaper';
	if (productId === 'framescaper') segments.shift();
	const embedded = segments[0] === 'embed';
	if (embedded) segments.shift();
	return createRoute(productId, segments[0] || 'en', embedded, false);
}

/**
 * The cross-origin transfer documents are not the application.
 *
 * In production they are standalone pages that load the transfer chunk
 * directly, generated by `scripts/generate-static-routes.mjs`. This branch is
 * what the dev server's SPA fallback reaches, and - more importantly - it is
 * the only reference that puts `transfer-page-entry.ts` into the production
 * module graph at all, which is how that chunk comes to exist for the generated
 * pages to point at. It is a dynamic import, so no editor session pays for it.
 *
 * It never resolves on purpose: the caller's next steps mount the editor shell,
 * and a transfer document must not do that. Nothing after the await in
 * `src/main.jsx` should run once the transfer page owns the document.
 *
 * @param {typeof globalThis} scope
 * @returns {Promise<never>}
 */
async function mountTransferDocument(scope) {
	const { mountTransferPageFromLocation } = await import('../transfer/transfer-page-entry.ts');
	await mountTransferPageFromLocation(scope);
	return new Promise(() => {});
}

function createRoute(productId, locale, embedded, desktop) {
	const descriptor = getLocaleDescriptor(locale) || getLocaleDescriptor('en');
	return Object.freeze({
		productId,
		locale: descriptor.locale,
		direction: descriptor.direction,
		embedded,
		desktop,
	});
}
